import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const sourceDir = path.join(root, "images/products");
const outDir = path.join(root, "public/img/products");
const manifestPath = path.join(root, "src/data/product-images.generated.ts");

// Thumbnails render at 64–72px, the homepage hero at 240px, the product page at 288px.
const widths = [160, 320, 640];
const formats = [
  { ext: "avif", options: { quality: 52, effort: 6 } },
  { ext: "webp", options: { quality: 74, effort: 6 } },
];

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const files = (await readdir(sourceDir)).filter((f) => f.endsWith(".jpg")).sort();
const manifest = {};

for (const file of files) {
  const slug = file.replace(/\.jpg$/, "");
  const input = await readFile(path.join(sourceDir, file));
  const hash = createHash("sha256").update(input).digest("hex").slice(0, 8);
  const base = `${slug}-${hash}`;
  const { dominant } = await sharp(input).stats();
  const toHex = (n) => n.toString(16).padStart(2, "0");

  for (const width of widths) {
    for (const { ext, options } of formats) {
      await sharp(input)
        .resize(width, width, { fit: "cover" })
        [ext](options)
        .toFile(path.join(outDir, `${base}-${width}.${ext}`));
    }
  }

  manifest[slug] = {
    base: `/img/products/${base}`,
    color: `#${toHex(dominant.r)}${toHex(dominant.g)}${toHex(dominant.b)}`,
  };
}

const body = `// Generated by scripts/build-images.mjs. Run \`npm run images\` after changing images/products.
export const productImageWidths = ${JSON.stringify(widths)} as const;

export const productImageFiles: Record<string, { base: string; color: string }> = ${JSON.stringify(manifest, null, 2)};
`;

await writeFile(manifestPath, body);
console.log(`Wrote ${files.length} images × ${widths.length} sizes × ${formats.length} formats.`);
